import type { Locale, TranslationResource } from '@/i18n'

type TranslationTree = { [key: string]: string | TranslationTree }

function flattenTranslations(tree: TranslationTree, prefix = ''): TranslationResource {
  return Object.entries(tree).reduce<TranslationResource>((translations, [key, value]) => {
    const path = prefix ? `${prefix}.${key}` : key
    if (typeof value === 'string') translations[path] = value
    else Object.assign(translations, flattenTranslations(value, path))
    return translations
  }, {})
}

